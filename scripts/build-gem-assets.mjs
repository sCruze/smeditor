#!/usr/bin/env node
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(__dirname, "..");
const entry = path.join(root, "gems/smeditor/frontend/index.ts");
const outDir = path.join(root, "gems/smeditor/app/assets/javascripts");
const outFile = path.join(outDir, "smeditor.js");

function loadTypeScript() {
  const localRequire = createRequire(import.meta.url);
  try { return localRequire("typescript"); } catch {}
  const npmRoot = execFileSync("npm", ["root", "-g"], { encoding: "utf8" }).trim();
  return localRequire(path.join(npmRoot, "typescript"));
}
const ts = loadTypeScript();

const packageMap = new Map();
for (const dirent of fs.readdirSync(path.join(root, "packages"), { withFileTypes: true })) {
  if (!dirent.isDirectory()) continue;
  const dir = path.join(root, "packages", dirent.name);
  const pkgFile = path.join(dir, "package.json");
  if (!fs.existsSync(pkgFile)) continue;
  const pkg = JSON.parse(fs.readFileSync(pkgFile, "utf8"));
  if (pkg.name) packageMap.set(pkg.name, dir);
}

function sourceEntry(dir) {
  for (const candidate of ["src/index.ts", "src/index.tsx", "src/index.js"]) {
    const file = path.join(dir, candidate);
    if (fs.existsSync(file)) return file;
  }
  throw new Error(`No source entry found in ${dir}`);
}

function resolveSource(fromFile, specifier) {
  if (specifier.startsWith("@smeditor/")) {
    const dir = packageMap.get(specifier);
    if (!dir) throw new Error(`Unknown SMEditor package: ${specifier}`);
    return sourceEntry(dir);
  }
  if (specifier.startsWith(".")) {
    const base = path.resolve(path.dirname(fromFile), specifier);
    const candidates = [
      base,
      base.replace(/\.js$/, ".ts"),
      base.replace(/\.js$/, ".tsx"),
      `${base}.ts`, `${base}.tsx`, `${base}.js`,
      path.join(base, "index.ts"), path.join(base, "index.tsx"), path.join(base, "index.js"),
    ];
    for (const candidate of candidates) if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate;
  }
  throw new Error(`Unsupported external import '${specifier}' from ${path.relative(root, fromFile)}`);
}

const modules = [];
const ids = new Map();

function addModule(file) {
  file = path.resolve(file);
  if (ids.has(file)) return ids.get(file);
  const id = modules.length;
  ids.set(file, id);
  modules.push(null);

  const source = fs.readFileSync(file, "utf8");
  const compiled = ts.transpileModule(source, {
    fileName: file,
    compilerOptions: {
      module: ts.ModuleKind.CommonJS,
      target: ts.ScriptTarget.ES2019,
      jsx: ts.JsxEmit.ReactJSX,
      esModuleInterop: true,
      importsNotUsedAsValues: ts.ImportsNotUsedAsValues.Remove,
      sourceMap: false,
    },
    reportDiagnostics: true,
  });
  const errors = (compiled.diagnostics || []).filter((d) => d.category === ts.DiagnosticCategory.Error);
  if (errors.length) {
    const message = errors.map((d) => ts.flattenDiagnosticMessageText(d.messageText, "\n")).join("\n");
    throw new Error(`${path.relative(root, file)}: ${message}`);
  }

  const mapping = {};
  const requireRe = /require\(["']([^"']+)["']\)/g;
  for (const match of compiled.outputText.matchAll(requireRe)) {
    const specifier = match[1];
    if (mapping[specifier] !== undefined) continue;
    mapping[specifier] = addModule(resolveSource(file, specifier));
  }
  modules[id] = { file, code: compiled.outputText, mapping };
  return id;
}

const entryId = addModule(entry);
const banner = `/* SMEditor Rails browser bundle. Generated by scripts/build-gem-assets.mjs.\n * Contains SMEditor core + starter/full extensions. No npm/runtime JS dependencies. */\n`;
let output = `${banner}(function(){\n"use strict";\nvar M={\n`;
output += modules.map((mod, id) => `${JSON.stringify(id)}:[function(require,module,exports){\n${mod.code}\n},${JSON.stringify(mod.mapping)}]`).join(",\n");
output += `\n},C={};\nfunction R(id){if(C[id])return C[id].exports;var x=M[id];if(!x)throw new Error("SMEditor module "+id+" not found");var m=C[id]={exports:{}};function r(s){var n=x[1][s];if(n===undefined)throw new Error("SMEditor dependency "+s+" not found");return R(n)}x[0](r,m,m.exports);return m.exports}R(${entryId});\n})();\n`;

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(outFile, output);
console.log(`Built ${path.relative(root, outFile)} (${Math.round(Buffer.byteLength(output) / 1024)} KiB, ${modules.length} modules)`);

let tokens = fs.readFileSync(path.join(root, "packages/theme-default/src/tokens.css"), "utf8");
// The Rails adapter renders the editor in a ShadowRoot so host-application CSS
// cannot mutate toolbar/content styles. Mirror the theme token selectors onto
// :host so the same stylesheet works both in the document and inside shadow DOM.
tokens = tokens
  .replace(':root,\n[data-theme="light"] {', ':root,\n:host,\n:host([data-theme="light"]),\n[data-theme="light"] {')
  .replace('/* Common (non-color) tokens — shared by both themes. */\n:root {', '/* Common (non-color) tokens — shared by both themes. */\n:root,\n:host {')
  .replace('[data-theme="dark"] {', ':host([data-theme="dark"]),\n[data-theme="dark"] {')
  .replace(':root:not([data-theme="light"]) {', ':root:not([data-theme="light"]),\n  :host(:not([data-theme="light"])) {');
let theme = fs.readFileSync(path.join(root, "packages/theme-default/src/index.css"), "utf8");
theme = theme.replace(/@import\s+["']\.\/tokens\.css["'];?\s*/m, "");
const railsExtras = `
/* Rails self-contained adapter / style isolation */
:host {
  display: block;
  width: 100%;
  color: var(--sme-color-text);
  font-family: var(--sme-font-sans);
  font-size: var(--sme-text-base);
  line-height: normal;
  text-align: initial;
}
.smeditor,
.smeditor *,
.smeditor *::before,
.smeditor *::after { box-sizing: border-box; }
.smeditor button,
.smeditor input,
.smeditor select,
.smeditor textarea {
  margin: 0;
  font: inherit;
  color: inherit;
  letter-spacing: normal;
  text-transform: none;
}
.smeditor button { -webkit-tap-highlight-color: transparent; }
.smeditor svg { display: block; flex: 0 0 auto; }
.smeditor-file-input { display: none !important; }
.smeditor-mount { width: 100%; }
`;
const cssDir = path.join(root, "gems/smeditor/app/assets/stylesheets");
fs.mkdirSync(cssDir, { recursive: true });
const cssFile = path.join(cssDir, "smeditor.css");
fs.writeFileSync(cssFile, `${tokens}\n${theme}\n${railsExtras}`);
console.log(`Built ${path.relative(root, cssFile)} (${Math.round(fs.statSync(cssFile).size / 1024)} KiB)`);
